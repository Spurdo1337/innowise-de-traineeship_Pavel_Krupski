-- ---------------------------------------------------------------------------
-- One-time Snowflake provisioning for the SADA project.
--
-- Run this file with an ACCOUNTADMIN account. The placeholders below are
-- substituted by scripts/bootstrap_snowflake.py; never commit rendered
-- versions of this file.
--
-- Objects created here:
--   database   SADA
--   schemas    PAGILA_RAW, SAKILA_RAW   (Airbyte landing zones)
--              STAGING, INTERMEDIATE, MARTS, ANALYTICS  (dbt layers)
--   warehouse  SADA_WH (XSMALL, auto-suspended)
--   roles      SADA_ADMIN (humans), SADA_DEV (Airflow + dbt),
--              SADA_INGEST (Airbyte)
--   users      AIRFLOW_SVC (SADA_DEV), AIRBYTE_SVC (SADA_INGEST)
-- ---------------------------------------------------------------------------

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS SADA;

CREATE SCHEMA IF NOT EXISTS SADA.PAGILA_RAW;
CREATE SCHEMA IF NOT EXISTS SADA.SAKILA_RAW;
CREATE SCHEMA IF NOT EXISTS SADA.STAGING;
CREATE SCHEMA IF NOT EXISTS SADA.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS SADA.MARTS;
CREATE SCHEMA IF NOT EXISTS SADA.ANALYTICS;

CREATE WAREHOUSE IF NOT EXISTS SADA_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS SADA_ADMIN;
CREATE ROLE IF NOT EXISTS SADA_DEV;
CREATE ROLE IF NOT EXISTS SADA_INGEST;

GRANT ROLE SADA_DEV TO ROLE SADA_ADMIN;
GRANT ROLE SADA_INGEST TO ROLE SADA_ADMIN;
GRANT ROLE SADA_ADMIN TO USER {{ADMIN_USER}};

GRANT USAGE ON WAREHOUSE SADA_WH TO ROLE SADA_ADMIN;
GRANT USAGE ON WAREHOUSE SADA_WH TO ROLE SADA_DEV;
GRANT USAGE ON WAREHOUSE SADA_WH TO ROLE SADA_INGEST;

GRANT USAGE ON DATABASE SADA TO ROLE SADA_ADMIN;
GRANT USAGE ON DATABASE SADA TO ROLE SADA_DEV;
GRANT USAGE ON DATABASE SADA TO ROLE SADA_INGEST;

-- Airbyte: write access to the raw landing schemas only.
GRANT CREATE SCHEMA ON DATABASE SADA TO ROLE SADA_INGEST;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE
    ON SCHEMA SADA.PAGILA_RAW TO ROLE SADA_INGEST;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STAGE
    ON SCHEMA SADA.SAKILA_RAW TO ROLE SADA_INGEST;

-- Airflow + dbt: read the raw layer, own the transformation schemas.
GRANT CREATE SCHEMA ON DATABASE SADA TO ROLE SADA_DEV;

GRANT USAGE ON SCHEMA SADA.PAGILA_RAW TO ROLE SADA_DEV;
GRANT USAGE ON SCHEMA SADA.SAKILA_RAW TO ROLE SADA_DEV;
GRANT SELECT ON ALL TABLES IN SCHEMA SADA.PAGILA_RAW TO ROLE SADA_DEV;
GRANT SELECT ON ALL TABLES IN SCHEMA SADA.SAKILA_RAW TO ROLE SADA_DEV;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SADA.PAGILA_RAW TO ROLE SADA_DEV;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SADA.PAGILA_RAW TO ROLE SADA_DEV;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SADA.SAKILA_RAW TO ROLE SADA_DEV;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SADA.SAKILA_RAW TO ROLE SADA_DEV;

GRANT ALL PRIVILEGES ON SCHEMA SADA.STAGING TO ROLE SADA_DEV;
GRANT ALL PRIVILEGES ON SCHEMA SADA.INTERMEDIATE TO ROLE SADA_DEV;
GRANT ALL PRIVILEGES ON SCHEMA SADA.MARTS TO ROLE SADA_DEV;
GRANT ALL PRIVILEGES ON SCHEMA SADA.ANALYTICS TO ROLE SADA_DEV;

CREATE USER IF NOT EXISTS AIRFLOW_SVC
    PASSWORD = '{{AIRFLOW_SVC_PASSWORD}}'
    DEFAULT_ROLE = SADA_DEV
    DEFAULT_WAREHOUSE = SADA_WH
    MUST_CHANGE_PASSWORD = FALSE;

CREATE USER IF NOT EXISTS AIRBYTE_SVC
    PASSWORD = '{{AIRBYTE_SVC_PASSWORD}}'
    DEFAULT_ROLE = SADA_INGEST
    DEFAULT_WAREHOUSE = SADA_WH
    MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE SADA_DEV TO USER AIRFLOW_SVC;
GRANT ROLE SADA_INGEST TO USER AIRBYTE_SVC;
